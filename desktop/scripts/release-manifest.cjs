'use strict';
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const desktop = path.join(__dirname, '..');
const version = JSON.parse(fs.readFileSync(path.join(desktop, 'package.json'), 'utf8')).version;
const tag = process.env.GITHUB_REF_NAME || `v${version}`;
const repository = process.env.GITHUB_REPOSITORY || 'the-shr/chronexa';
if (!/^\d+\.\d+\.\d+$/.test(version) || tag !== `v${version}` || repository !== 'the-shr/chronexa') throw new Error('Stable release version/tag/repository mismatch');
const directory = process.env.CHRONEXA_RELEASE_DIR || path.join(desktop, 'release');
const filename = `Chronexa.Setup.${version}.exe`;
const target = path.join(directory, filename);
if (!fs.existsSync(target)) fs.copyFileSync(path.join(directory, `Chronexa Setup ${version}.exe`), target);
const checksum = crypto.createHash('sha256').update(fs.readFileSync(target)).digest('hex');
const notesFile = path.join(desktop, 'update-notes.txt');
const notes = fs.existsSync(notesFile) ? fs.readFileSync(notesFile, 'utf8').trim().slice(0, 400) : 'Install the latest Chronexa update.';
const manifest = { product: 'Chronexa', latestVersion: version, downloadUrl: `https://github.com/${repository}/releases/download/${tag}/${filename}`, downloadSha256: checksum, releaseNotesUrl: `https://github.com/${repository}/releases/tag/${tag}`, notes };
fs.writeFileSync(path.join(directory, 'update.json'), JSON.stringify(manifest, null, 2) + '\n');
fs.writeFileSync(path.join(directory, 'SHA256SUMS.txt'), `${checksum}  ${filename}\n`);
console.log(`Prepared ${filename}, update.json and SHA256SUMS.txt`);
