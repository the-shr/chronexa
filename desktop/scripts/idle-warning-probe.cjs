const { app, BrowserWindow, ipcMain } = require('electron');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const output = process.env.CHRONEXA_TEST_OUTPUT || path.join(app.getPath('temp'), `chronexa-idle-${Date.now()}`);
fs.mkdirSync(output, { recursive: true });
app.setPath('userData', path.join(output, 'user-data'));
app.on('window-all-closed', () => {});
const desktop = path.join(__dirname, '..');
const settings = require(path.join(desktop, 'electron/lib/settings'));
const db = require(path.join(desktop, 'electron/lib/db'));
const tracker = require(path.join(desktop, 'electron/lib/tracker'));
const updater = require(path.join(desktop, 'electron/lib/updater'));
const policy = require(path.join(desktop, 'electron/lib/update-policy'));
const windows = require(path.join(desktop, 'electron/lib/windows'));
const pause = (ms) => new Promise((resolve) => setTimeout(resolve, ms));
async function until(check) { const end = Date.now() + 10000; while (Date.now() < end) { if (await check()) return; await pause(50); } throw new Error('Idle popup confirmation timed out'); }
app.whenReady().then(async () => {
  settings.init(); db.init();
  settings.set({ screenshots: { enabled: false }, general: { autoUpdate: false } });
  updater.check = async () => ({ currentVersion: app.getVersion(), latestVersion: app.getVersion(), available: false, required: false });
  policy.init(); await policy.refresh();
  ipcMain.handle('tracker:snapshot', () => tracker.snapshot());
  ipcMain.handle('settings:get', () => settings.publicView());
  ipcMain.handle('tracker:acknowledge-idle', () => { const snapshot = tracker.acknowledgeIdle(); windows.closeIdleWindow(); return snapshot; });
  ipcMain.handle('window:close-idle-warning', () => windows.closeIdleWindow());
  app.on('browser-window-created', (_event, win) => { win.setFocusable(false); win.once('ready-to-show', () => win.setPosition(-20000, -20000)); });
  tracker.on('state', (snapshot) => windows.broadcast('tracker:state', snapshot));
  tracker.on('idle-warning', (payload) => {
    const win = windows.openIdleWindow();
    win.webContents.once('did-finish-load', () => windows.broadcast('tracker:idle-warning', { ...payload, playSound: false }));
  });
  tracker.start(); tracker.session.activeSeconds = 600;
  const beforeWarning = tracker.snapshot().today.workSeconds;
  tracker.enterIdle(settings.get(), Date.now());
  assert.equal(tracker.snapshot().today.workSeconds, beforeWarning, 'Opening the popup must not deduct work');
  const win = windows.getIdleWindow();
  await until(() => win.webContents.executeJavaScript("[...document.querySelectorAll('button')].some(button => button.textContent.includes(\"I'm still here\"))"));
  fs.writeFileSync(path.join(output, 'popup.png'), (await win.webContents.capturePage()).toPNG());
  await win.webContents.executeJavaScript("[...document.querySelectorAll('button')].find(button => button.textContent.includes(\"I'm still here\")).click()");
  await until(() => tracker.idlePhase === 'active');
  await pause(1500);
  assert.equal(tracker.idlePhase, 'active', 'Confirmation must not immediately open another idle warning');
  assert.ok(tracker.snapshot().today.workSeconds >= beforeWarning, 'Clicking the real presence button must not lose minutes');
  assert.equal(tracker.session.idleSeconds, 0); assert.equal(tracker.session.pendingIdleSeconds, 0);
  tracker.stop('test'); db.flush();
  BrowserWindow.getAllWindows().forEach((window) => window.destroy());
  fs.writeFileSync(path.join(output, 'result.txt'), 'PASS: real idle popup and IPC confirmation retain ten minutes, close the warning and persist zero pending idle');
  app.quit();
}).catch((error) => { fs.writeFileSync(path.join(output, 'result.txt'), error.stack); if (tracker.state !== 'stopped') tracker.stop('test-error'); app.exit(1); });
